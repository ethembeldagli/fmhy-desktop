/**
 * Generates the service marks FMHY uses beside supplementary links.
 *
 * Their site draws these from the Carbon and MDI icon sets (see the UnoCSS
 * safelist in fmhy/edit). Using the same sources means Discord, GitHub and the
 * rest are the identical glyphs rather than approximations.
 *
 * These are single-colour, so they are emitted as CSS masks and take the
 * surrounding text colour — unlike the Twemoji set, which is full-colour
 * artwork and must be a background image.
 *
 * Run with: node scripts/gen-service-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const WANTED = [
  ['discord', 'carbon', 'logo-discord'],
  ['github', 'carbon', 'logo-github'],
  ['x', 'carbon', 'logo-x'],
  ['youtube', 'carbon', 'logo-youtube'],
  ['reddit', 'mdi', 'reddit'],
  ['telegram', 'mdi', 'telegram'],
]

const sets = {}
for (const pkg of ['carbon', 'mdi']) {
  const path = fileURLToPath(
    new URL(`../node_modules/@iconify-json/${pkg}/icons.json`, import.meta.url),
  )
  sets[pkg] = JSON.parse(readFileSync(path, 'utf8'))
}

const entries = []
for (const [key, pkg, name] of WANTED) {
  const set = sets[pkg]
  const icon = set.icons[name]
  if (!icon) {
    console.error(`missing ${pkg}:${name}`)
    process.exitCode = 1
    continue
  }
  const w = icon.width ?? set.width ?? 24
  const h = icon.height ?? set.height ?? 24
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${icon.body}</svg>`
  const encoded = encodeURIComponent(svg)
    .replace(/'/g, '%27')
    .replace(/\(/g, '%28')
    .replace(/\)/g, '%29')
  entries.push(`  ${key}: '${encoded}',`)
}

const out = `// GENERATED by scripts/gen-service-icons.mjs — do not edit.
//
// Carbon (Apache-2.0) and MDI (Apache-2.0) via @iconify-json, the same sets
// FMHY's site uses for these marks.

export type ServiceIconName =
${entries.map((e) => `  | '${e.trim().split(':')[0]}'`).join('\n')}

const SOURCES: Record<ServiceIconName, string> = {
${entries.join('\n')}
}

/** A \`url()\` value for the given mark, for use as a CSS mask. */
export function serviceIconUrl(name: ServiceIconName): string {
  return \`url("data:image/svg+xml,\${SOURCES[name]}")\`
}
`

writeFileSync(
  fileURLToPath(new URL('../src/ui/components/serviceIcons.generated.ts', import.meta.url)),
  out,
)
console.log(`wrote ${entries.length} service icons (${(out.length / 1024).toFixed(1)} KB)`)
